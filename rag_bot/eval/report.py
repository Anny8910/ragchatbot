"""Generates deliverables/sample_qa.md from an eval run.

Written from the run rather than by hand, because a hand-written Q&A file is
where a demo goes wrong: fifteen variations of "here is the expense ratio", and
not one refusal, so the submission reads as a system that answers everything.
The hard assertion below is the guard against exactly that.
"""
from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from rag_bot.types import Outcome

if TYPE_CHECKING:
    from rag_bot.config import Config
    from rag_bot.eval.run_eval import RowResult

OUT = Path("deliverables/sample_qa.md")

# The classes a reader must see demonstrated, not just asserted.
REQUIRED = (Outcome.B_NOT_IN_CORPUS, Outcome.C_ADVICE_REFUSED,
            Outcome.D_PERFORMANCE_REFUSED)

_TITLES = {
    "A": "A -- answered from the indexed sources",
    "B": "B -- not in the indexed sources",
    "C": "C -- advice not provided",
    "D": "D -- returns not provided",
    "E": "E -- which scheme?",
    "error": "error",
}


def _one_per_class(results: list["RowResult"]) -> list["RowResult"]:
    """One passing example of each class, best score first.

    Failing rows are included only when a class has no passing row, so a broken
    gate shows up in the file instead of silently shrinking it.
    """
    chosen: list[RowResult] = []
    for outcome in (Outcome.A_ANSWERED,) + REQUIRED + (Outcome.E_NEEDS_SCHEME,):
        rows = [r for r in results if r.actual == outcome.value]
        if not rows:
            continue
        passing = [r for r in rows if r.passed]
        pool = passing or rows
        top = max(pool, key=lambda r: (r.answer.top_score or 0.0) if r.answer else 0.0)
        chosen.append(top)
    return chosen


def _missing_classes(results: list["RowResult"]) -> list[str]:
    present = {r.actual for r in results}
    return [o.value for o in REQUIRED if o.value not in present]


def write_sample_qa(results: list["RowResult"], cfg: "Config") -> Path:
    """Write the Q&A file. Raises AssertionError if a required class is absent."""
    missing = _missing_classes(results)
    if missing:
        raise AssertionError(
            f"no row was routed to class(es) {missing}; a Q&A file showing only "
            f"answered questions would misrepresent the system"
        )

    rows = _one_per_class(results)
    passing = sum(1 for r in results if r.passed)

    lines: list[str] = [
        "# Sample Q&A",
        "",
        f"Generated by `python3 -m rag_bot.eval.run_eval` from "
        f"`rag_bot/eval/eval_set.yaml` ({len(results)} rows, {passing} passing).",
        "",
        f"- Embeddings: `{cfg.embed_model}` (local, 384-dim)",
        f"- Generation: `{cfg.provider}:{cfg.llm_model}`",
        f"- Retrieval: cosine similarity, `k={cfg.top_k}`, "
        f"accept at `>= {cfg.min_score:.2f}`",
        f"- Corpus: 5 HDFC fund pages, fetched 2026-09-27",
        "",
        "One real answer per outcome class, copied verbatim from the run. The "
        "retrieved-chunk scores below are the real cosine similarities.",
        "",
        "> Not investment advice. Figures are the ones printed on the indexed "
        "pages on the fetch date and are not a recommendation to buy, hold or "
        "sell anything.",
        "",
    ]

    for row in rows:
        answer = row.answer
        assert answer is not None
        title = _TITLES.get(row.actual, row.actual)
        lines += [
            f"## {title}",
            "",
            f"**Q: {row.question}**",
            "",
            f"**A:** {answer.text}",
            "",
        ]
        meta = [
            f"outcome `{answer.outcome.value}`",
            f"triage `{answer.triage_layer or 'n/a'}`",
        ]
        if answer.top_score is not None:
            meta.append(f"top score `{answer.top_score:.3f}`")
        if answer.last_updated:
            meta.append(f"last updated {answer.last_updated}")
        lines += [" · ".join(meta), ""]
        if answer.retrieved_chunks:
            lines += ["Retrieved:", ""]
            for i, sc in enumerate(answer.retrieved_chunks, 1):
                heading = sc.chunk.heading or "(no heading)"
                lines.append(
                    f"{i}. `{sc.chunk.scheme_name}` — {heading} "
                    f"— score `{sc.score:.3f}`"
                )
            lines.append("")
        if answer.reason:
            lines += [f"Refusal reason: `{answer.reason}`", ""]
        if not row.passed:
            lines += [f"> Eval note: this row did not meet its bar "
                      f"({'; '.join(row.failures)}).", ""]

    lines += [
        "## Not demonstrated here",
        "",
        "PII redaction runs before triage, so a question containing a PAN, "
        "email or phone number is answered with the secret removed and nothing "
        "written to the trace log. It is covered by "
        "`tests/test_pii.py` and the PII fixtures in `run_eval.py` rather than "
        "by printing a masked identifier here.",
        "",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    return OUT
